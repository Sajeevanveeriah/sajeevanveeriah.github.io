/**
 * The completeness contract.
 *
 * Every term in the supplied scope gets a row here, recorded in the spelling
 * it was supplied in, and resolved to a canonical entity. That makes
 * coverage a derived number rather than an assertion: the validator fails
 * on a term that resolves to nothing, and the interface reports the totals
 * straight off this table.
 *
 * `resolution` records how the term was absorbed:
 *   canonical    the term is the entity's own name
 *   alias        a vendor spelling, abbreviation or common variant
 *   model        a specific generation or variant inside a family
 *   former-name  the thing was renamed, and this is what it used to be
 *   lifecycle-note  the term named something now retired, deprecated or superseded
 *   correction   the supplied term was wrong, duplicated or ambiguous, and the
 *                note records what was done about it
 *
 * "Complete" here means complete within this declared scope. No finite
 * catalogue can contain every engineering product, which is why the schema
 * is extensible and why the interface says so in as many words.
 */

